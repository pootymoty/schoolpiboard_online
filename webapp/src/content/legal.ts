/**
 * Правовые документы сервиса.
 *
 * Вынесены из страницы отдельно: это текст, а не разметка, и править его
 * будут по юридическому поводу, а не по вёрстке. Реквизиты подставляются
 * из одного места — расхождение в них видно и покупателю, и проверяющему.
 *
 * Документов три, и они отвечают на разные вопросы. Оферта — договор о
 * платной подписке: предмет, цена, сроки, возврат. Соглашение — правила
 * пользования сервисом, в том числе бесплатного. Политика — что сервис
 * делает с персональными данными. Смешивать их нельзя: платёжная система
 * при проверке смотрит именно оферту, и она должна читаться как договор,
 * а не как страница помощи.
 *
 * Тексты написаны под то, что сервис делает на самом деле. Документ,
 * расходящийся с поведением, хуже отсутствующего: на него сошлются, и
 * отвечать придётся по написанному.
 */

/** Блок внутри раздела: абзац, перечень или таблица «свойство — значение». */
export type Block =
  | { readonly kind: 'p'; readonly text: string }
  | { readonly kind: 'list'; readonly items: readonly string[] }
  | { readonly kind: 'rows'; readonly caption: string; readonly rows: readonly (readonly [string, string])[] };

export interface Section {
  readonly title: string;
  readonly blocks: readonly Block[];
}

export interface LegalDocument {
  readonly title: string;
  readonly lead?: string;
  readonly sections: readonly Section[];
}

const p = (text: string): Block => ({ kind: 'p', text });
const list = (...items: string[]): Block => ({ kind: 'list', items });

