/**
 * Правила названия доски — те же, что проверяет сервер (BoardService):
 * русские и английские буквы, цифры и пробелы, не длиннее 50 символов.
 */
export const BOARD_TITLE_MAX = 50;

export const BOARD_TITLE_HINT = `Буквы (русские или английские), цифры и пробелы — до ${BOARD_TITLE_MAX} символов.`;

/**
 * Чистит ввод на лету: лишний символ просто не появляется в поле, в
 * том числе при вставке из буфера, — вместо ошибки уже после нажатия
 * «Создать». Пробелы подряд схлопываются в один, как и на сервере.
 */
export function cleanBoardTitle(value: string): string {
  return value
    .replace(/[^A-Za-zА-Яа-яЁё0-9 ]/g, '')
    .replace(/ {2,}/g, ' ')
    .slice(0, BOARD_TITLE_MAX);
}
