import type { ReactElement } from 'react';

/**
 * Знак «Пи» — персонаж с прозрачным фоном, стоит прямо в строке текста,
 * а не в цветном квадрате. Размер задаётся через `em`, чтобы знак
 * масштабировался вместе со шрифтом в каждом месте, где он встречается.
 */
export function PiMark(): ReactElement {
  return <img src="/pi-mark.png" alt="Пи" className="pi-mark" />;
}

/**
 * «Школа Пи» со знаком вместо буквы — только для меню и шапки: это
 * ссылка на вторую программу автора, и такой логотип имеет смысл ровно
 * там, где он ведёт на неё. В остальном тексте (описания, подвал) имя
 * пишется обычными буквами — картинка через каждое упоминание не
 * добавляет ясности, только рябит.
 *
 * Одним `<span>`, а не двумя текстовыми узлами вперемешку с картинкой:
 * иначе в строке с `justify-content: space-between` (пункт меню, ссылка
 * в шапке) знак считался бы отдельным элементом и раздвигался от слова
 * «Школа» на всю доступную ширину.
 */
export function SchoolPiLabel(): ReactElement {
  return <span className="pi-label">Школа <PiMark /></span>;
}

/** Знак самой доски — картинка с доской и мелом, та же, что в фавиконке. */
export function BoardMark(): ReactElement {
  return <img src="/board-mark.png" alt="Пи" className="pi-mark" />;
}
