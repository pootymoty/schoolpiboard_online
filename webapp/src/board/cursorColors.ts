/**
 * Цвета чужих курсоров.
 *
 * Двадцать оттенков, разнесённых по кругу и различимых на светлом и на
 * тёмном фоне. Цвет закрепляется за подключением, а не выдаётся по
 * очереди: тогда он одинаков у всех, кто смотрит на доску, и «синий
 * курсор» означает для всех одного и того же человека.
 */
const CURSOR_COLORS = [
  '#C0392B', '#E67E22', '#D68910', '#B7950B', '#7D8C1F',
  '#4E9A2F', '#1E8449', '#149174', '#12877F', '#1595A6',
  '#1F78A8', '#2471A3', '#2E5FA3', '#4A4FA8', '#6C4AA8',
  '#8E44AD', '#A63A8F', '#B03A6E', '#B03A4E', '#8C5B3F',
];

/**
 * Цвет по идентификатору подключения. Хеш простой и стабильный —
 * важно не распределение, а то, чтобы у всех совпало.
 */
export function cursorColor(connectionId: string): string {
  let hash = 0;

  for (let index = 0; index < connectionId.length; index += 1) {
    hash = (hash * 31 + connectionId.charCodeAt(index)) | 0;
  }

  return CURSOR_COLORS[Math.abs(hash) % CURSOR_COLORS.length];
}
