-- Убираем дату рождения.
--
-- Она нигде не использовалась, кроме проверки «возраст от 6 до 120 лет»
-- при регистрации: ни на подписку, ни на доски, ни на роли не влияла и
-- в интерфейсе не показывалась. Хранить персональные данные, которые ни на
-- что не влияют, — лишняя обязанность по их защите без всякой пользы,
-- поэтому колонки удаляются вместе с уже накопленными значениями.
--
-- Скрипт для баз, созданных до этой правки: в 001_init.sql колонок уже нет,
-- так что при установке с нуля здесь просто нечего удалять. Как и остальные
-- скрипты, выполняется при каждом старте сервиса, поэтому IF EXISTS
-- обязателен.

ALTER TABLE users                 DROP COLUMN IF EXISTS birth_date;
ALTER TABLE pending_registrations DROP COLUMN IF EXISTS birth_date;
