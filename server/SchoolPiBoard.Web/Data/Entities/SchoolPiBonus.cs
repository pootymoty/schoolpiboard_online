namespace SchoolPiBoard.Web.Data.Entities;

/// <summary>
/// Бонус за вход через «Школу π»: неделя тарифа «Расширенный».
///
/// Выдаётся один раз — и на учётную запись доски, и на аккаунт школы.
/// Отметка лежит отдельной таблицей, без внешнего ключа на users:
/// строку удалённой учётной записи через полгода стирает зачистка, и
/// вместе с ней пропала бы память о том, что этому аккаунту школы
/// бонус уже давали, — а значит, его можно было бы получать заново,
/// заводя на доске новую учётную запись.
///
/// Пишется и тогда, когда бонус не выдан (действует тариф выше): решение
/// принимается один раз, при привязке, и повторно не пересматривается.
/// </summary>
public class SchoolPiBonus
{
    public long Id { get; set; }

    /// <summary>Номер пользователя в «Школе π».</summary>
    public string ExternalId { get; set; } = string.Empty;

    public long UserId { get; set; }

    /// <summary>Выданный срок. Пусто — бонус не выдан: уже действовал тариф выше.</summary>
    public long? SubscriptionId { get; set; }

    public DateTime CreatedAt { get; set; }
}
