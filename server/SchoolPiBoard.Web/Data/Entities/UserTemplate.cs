namespace SchoolPiBoard.Web.Data.Entities;

/// <summary>
/// Своя заготовка — набор объектов, сохранённый учителем под именем.
///
/// Принадлежит человеку, а не доске: заготовку затем и делают, чтобы
/// поставить её на следующем занятии и на другой доске. Поэтому она
/// переживает и доску, и страницу, на которой её собрали.
///
/// Внутри — те же объекты доски, что и в буфере обмена: тип и оформление,
/// без номеров и без ссылок на файлы. Картинки в заготовку не попадают
/// намеренно: файл принадлежит своей доске и уйдёт вместе с ней, а
/// заготовка осталась бы с пустой рамкой вместо картинки.
/// </summary>
public class UserTemplate
{
    /// <summary>
    /// Сколько заготовок помещается у одного человека.
    ///
    /// Предел щедрый: заготовки маленькие. Он защищает не от учителя, а
    /// от того, кто решит сложить в них свою библиотеку целиком.
    /// </summary>
    public const int MaxPerUser = 200;

    /// <summary>Предел на одну заготовку. Чертёж с подписями — это килобайты.</summary>
    public const int MaxBodyLength = 256 * 1024;

    public const int MaxTitleLength = 80;

    public long Id { get; set; }

    public long UserId { get; set; }

    public string Title { get; set; } = string.Empty;

    /// <summary>Объекты заготовки одним куском JSON — так же, как оформление объекта.</summary>
    public string Body { get; set; } = "[]";

    /// <summary>Сколько объектов внутри. Показывается в списке, чтобы не разбирать JSON ради числа.</summary>
    public int Count { get; set; }

    public DateTime CreatedAt { get; set; }

    public User? User { get; set; }
}
